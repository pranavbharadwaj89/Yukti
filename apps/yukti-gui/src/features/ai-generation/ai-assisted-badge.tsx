import type { AiAttribution } from "@/services/types";

/**
 * D5-T7 (CLAUDE.md principle 3): marks a step the AI generated. Confidence is the backend's own
 * D5-T6 formula value, shown as-is — never re-derived or guessed here; a missing value says
 * "confidence unavailable" rather than inventing one.
 */
export function AiAssistedBadge({ attribution }: { attribution: AiAttribution }) {
  const confidence =
    typeof attribution.confidence === "number"
      ? `${Math.round(attribution.confidence * 100)}% confidence`
      : "confidence unavailable";
  const detail = `Generated by ${attribution.capability} (${attribution.modelIdentifier}, prompt ${attribution.promptVersion}). Review before publishing.`;

  return (
    <span
      className="inline-flex items-center gap-1 rounded-full bg-info-soft px-2.5 py-0.5 text-xs font-medium text-info"
      title={detail}
    >
      AI-assisted · {confidence}
      <span className="sr-only">. {detail}</span>
    </span>
  );
}
