import { createRequire } from 'node:module';
import { expect, test, type Page } from '@playwright/test';

/**
 * D5-T7 / Day 5 exit check: English → Draft → publish → run, through the real browser UI, the real
 * API, a real Postgres, and the real flow engine. The only canned piece is the AI's answer
 * (ADR-0005: `Ai:Provider=fixture`, e2e/fixtures/ai/*.json) — no live AI call is ever made here.
 */

const ADMIN_EMAIL = process.env.E2E_ADMIN_EMAIL ?? 'admin@yukti.local';
const ADMIN_PASSWORD = process.env.E2E_ADMIN_PASSWORD ?? 'ChangeMe123!';

const require = createRequire(import.meta.url);
const AXE_SCRIPT = require.resolve('axe-core/axe.min.js');

async function signIn(page: Page) {
  await page.goto('/login');
  await page.getByLabel('Email').fill(ADMIN_EMAIL);
  await page.getByLabel('Password').fill(ADMIN_PASSWORD);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await expect(page).not.toHaveURL(/\/login$/);
}

/** Serious/critical WCAG 2.1 A/AA violations inside `selector`, in a real browser (contrast included, unlike jsdom). */
async function seriousAxeViolations(page: Page, selector: string) {
  await page.addScriptTag({ path: AXE_SCRIPT });
  return page.evaluate(async (scope) => {
    const axe = (window as unknown as { axe: { run: (ctx: unknown, opts: unknown) => Promise<{ violations: { id: string; impact: string | null; help: string }[] }> } }).axe;
    const result = await axe.run(scope, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa'] } });
    return result.violations
      .filter((v) => v.impact === 'serious' || v.impact === 'critical')
      .map((v) => `${v.impact}: ${v.id} — ${v.help}`);
  }, selector);
}

test('English → AI Draft → publish → run passes, end to end', async ({ page }) => {
  await signIn(page);
  await page.goto('/flows');

  const panel = page.getByRole('region', { name: 'Suggest a flow with AI' });
  await expect(panel).toBeVisible();
  expect(await seriousAxeViolations(page, 'section[aria-label="Suggest a flow with AI"]')).toEqual([]);

  await panel.getByLabel(/describe a test/i).fill('Check the Yukti API is up and reports its own service name');
  await panel.getByRole('button', { name: 'Suggest a flow' }).click();

  // Lands on the generated Draft in the normal editor — never auto-published.
  await expect(page).toHaveURL(/\/flows\/[0-9a-f-]{36}$/);
  await expect(page.getByText('Draft', { exact: true })).toBeVisible();
  await expect(page.getByText('AI-assisted · 90% confidence').first()).toBeVisible();
  await expect(page.getByText('This draft was generated by AI. Review every step before publishing.')).toBeVisible();
  await expect(page.getByText('Steps (2)')).toBeVisible();

  // The human disposes: publishing is an explicit, separate action.
  await page.getByRole('button', { name: 'Publish' }).click();
  await expect(page.getByText('Published', { exact: true })).toBeVisible();

  await page.getByRole('button', { name: 'Run' }).click();
  await expect(page).toHaveURL(/\/runs\/[0-9a-f-]{36}$/);
  // Two real HTTP steps against the API itself, the second built from the first's saveAs output.
  await expect(page.getByText('Passed', { exact: true }).first()).toBeVisible();
  await expect(page.getByText('Failed', { exact: true })).toHaveCount(0);
});

test('client-side guardrails: empty and over-4000-character input never reach the API', async ({ page }) => {
  await signIn(page);
  await page.goto('/flows');
  const panel = page.getByRole('region', { name: 'Suggest a flow with AI' });

  const generateCalls: string[] = [];
  page.on('request', (req) => {
    if (req.url().includes('/api/v1/flows/generate')) generateCalls.push(req.url());
  });

  const button = panel.getByRole('button', { name: 'Suggest a flow' });
  await expect(button).toBeDisabled();

  await panel.getByLabel(/describe a test/i).fill('a'.repeat(4001));
  await expect(panel.getByText(/too long/i)).toBeVisible();
  await expect(button).toBeDisabled();

  expect(generateCalls).toEqual([]);
});
